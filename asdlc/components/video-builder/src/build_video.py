#!/usr/bin/env python3
"""Source-first ASDLC narrated-video proof of concept. Offline eSpeak is a test adapter."""
import argparse, hashlib, json, re, shutil, subprocess, sys, wave
from pathlib import Path

NOTES = ('speaker-notes-01-intro.md','speaker-notes-02-walkthrough.md','speaker-notes-03-details.md')

def run(*args):
    p=subprocess.run(args,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True)
    if p.returncode: raise RuntimeError(f"Command failed: {' '.join(map(str,args))}\n{p.stderr[-1600:]}")
    return p.stdout

def clean_markdown(raw):
    lines=[]
    for line in raw.splitlines():
        if line.startswith(('AI-MODIFIED - ','PME-APPROVED - ','# ')): continue
        if line.lstrip().startswith('<!--'): continue
        line=re.sub(r'\[([^]]+)\]\([^)]+\)',r'\1',line)
        line=re.sub(r'[`*_]','',line).strip()
        if line:lines.append(line)
    return '\n'.join(lines)

def slides_at(root):
    slides=[]
    for folder in sorted(root.iterdir()):
        if not folder.is_dir() or folder.name=='build':continue
        if not re.fullmatch(r'\d{2}-[a-z0-9-]+',folder.name):raise ValueError(f'Unexpected folder: {folder}')
        visual=folder/'slide.svg'
        if not visual.exists():raise ValueError(f'Missing visual: {visual}')
        files=[folder/name for name in NOTES if (folder/name).exists()]
        if not files or files[0].name!=NOTES[0]:raise ValueError(f'Missing introduction: {folder}')
        text='\n\n'.join(clean_markdown(p.read_text()) for p in files)
        if not text.strip():raise ValueError(f'Empty narration: {folder}')
        slides.append((folder,visual,files,text))
    if not slides:raise ValueError('No slides found')
    if [int(x[0].name[:2]) for x in slides]!=list(range(1,len(slides)+1)):
        raise ValueError('Slide numbering must be contiguous')
    return slides

def duration(path):
    return float(run('ffprobe','-v','error','-show_entries','format=duration','-of','default=noprint_wrappers=1:nokey=1',str(path)).strip())

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def build(root, count=None, voice='en', rate=155, profile='detailed'):
    import cairosvg
    for cmd in ('ffmpeg','ffprobe','espeak'):
        if not shutil.which(cmd):raise RuntimeError(f'Missing required tool: {cmd}')
    source=slides_at(root)
    if count:source=source[:count]
    output=root/'build';output.mkdir(exist_ok=True)
    pieces=[]; entries=[]; scripts=[]
    for n,(folder,visual,note_files,text) in enumerate(source,1):
        if profile=='intro':
            note_files=note_files[:1]
            text=clean_markdown(note_files[0].read_text())
        img=output/f'{n:02}-slide.png';wav=output/f'{n:02}-narration.wav';clip=output/f'{n:02}-scene.mp4'
        cairosvg.svg2png(url=str(visual),write_to=str(img),output_width=1920,output_height=1080)
        # Local eSpeak adapter: deterministic plumbing test, not production-quality voice.
        run('espeak','-v',voice,'-s',str(rate),'-w',str(wav),text)
        seconds=duration(wav)
        run('ffmpeg','-y','-loglevel','error','-loop','1','-framerate','1','-i',str(img),'-i',str(wav),'-c:v','libx264','-preset','ultrafast','-tune','stillimage','-pix_fmt','yuv420p','-r','24','-c:a','aac','-b:a','128k','-t',f'{seconds:.4f}','-shortest',str(clip))
        pieces.append(clip)
        scripts.append(text)
        entries.append({'slide':n,'source_folder':folder.name,'visual_sha256':sha(visual),'narration_sources':[{'file':p.name,'sha256':sha(p)} for p in note_files],'script_sha256':hashlib.sha256(text.encode()).hexdigest(),'characters':len(text),'audio_duration_seconds':round(seconds,3)})
    concat=output/'concat.txt'
    concat.write_text(''.join(f"file '{p.name}'\n" for p in pieces))
    target=output/f'{root.name}-{profile}-video-poc.mp4'
    run('ffmpeg','-y','-loglevel','error','-f','concat','-safe','0','-i',str(concat),'-c','copy',str(target))
    manifest={'status':'proof-of-concept','tts_provider':'espeak-local','tts_voice':voice,'tts_rate':rate,'narration_profile':profile,'source_slide_count':len(source),'video_duration_seconds':round(duration(target),3),'video_sha256':sha(target),'slides':entries,'caveat':'Audio was generated by local eSpeak for pipeline validation. Not a human-approved voice or a speech-fidelity certification.'}
    (output/'video-build-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (output/'narration-script.md').write_text('\n\n'.join(f'# Slide {i+1}\n\n{t}' for i,t in enumerate(scripts))+'\n')
    return target,manifest

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('presentation',type=Path);p.add_argument('--slides',type=int);p.add_argument('--voice',default='en');p.add_argument('--rate',type=int,default=155);p.add_argument('--profile',choices=('intro','detailed'),default='detailed');args=p.parse_args()
    target,manifest=build(args.presentation,args.slides,args.voice,args.rate,args.profile)
    print(json.dumps({'output':str(target),'slides':manifest['source_slide_count'],'duration_seconds':manifest['video_duration_seconds']},indent=2))
